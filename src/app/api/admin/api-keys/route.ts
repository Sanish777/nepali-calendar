import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { generateApiKey } from "@/lib/auth/api-key";
import { verifyToken } from "@/lib/auth/jwt";

function requireAdmin(req: NextRequest) {
  const token = req.cookies.get("miti_token")?.value;
  if (!token) return null;
  const session = verifyToken(token);
  return session?.role === "ADMIN" ? session : null;
}

export async function GET(req: NextRequest) {
  const admin = requireAdmin(req);
  if (!admin) return NextResponse.json({ success: false, message: "Forbidden" }, { status: 403 });

  const url = new URL(req.url);
  const search = url.searchParams.get("search")?.trim();
  const page = Math.max(parseInt(url.searchParams.get("page") || "1", 10) || 1, 1);
  const limit = Math.min(
    Math.max(parseInt(url.searchParams.get("limit") || "10", 10) || 10, 1),
    100
  );

  const where: any = {};
  if (search) {
    where.OR = [
      { keyPrefix: { contains: search, mode: "insensitive" } },
      { name: { contains: search, mode: "insensitive" } },
      { user: { name: { contains: search, mode: "insensitive" } } },
      { user: { email: { contains: search, mode: "insensitive" } } },
    ];
  }

  const [total, data] = await Promise.all([
    prisma.apiKey.count({ where }),
    prisma.apiKey.findMany({
      where,
      orderBy: { createdAt: "desc" },
      skip: (page - 1) * limit,
      take: limit,
      include: {
        user: {
          select: {
            name: true,
            email: true,
            subscription: {
              select: {
                customRpm: true,
                customMonthlyLimit: true,
                plan: {
                  select: {
                    requestsPerMinute: true,
                    monthlyRequestLimit: true,
                  },
                },
              },
            },
          },
        },
      },
    }),
  ]);

  return NextResponse.json({
    success: true,
    data,
    total,
    page,
    limit,
    totalPages: Math.max(Math.ceil(total / limit), 1),
  });
}

export async function POST(req: NextRequest) {
  const admin = requireAdmin(req);
  if (!admin) return NextResponse.json({ success: false, message: "Forbidden" }, { status: 403 });

  const body = await req.json();
  const { userId, customRpm, customMonthlyLimit, expiresAt } = body;

  if (!userId) {
    return NextResponse.json({ success: false, message: "userId is required" }, { status: 400 });
  }

  const { fullKey, keyPrefix } = generateApiKey();

  const apiKey = await prisma.apiKey.create({
    data: {
      userId,
      name: "Generated by Admin",
      key: fullKey,
      keyPrefix: keyPrefix,
      rateLimitPerMinute: customRpm ? parseInt(customRpm, 10) : null,
      monthlyLimit: customMonthlyLimit ? parseInt(customMonthlyLimit, 10) : null,
      expiresAt: expiresAt ? new Date(expiresAt) : null,
    },
  });

  return NextResponse.json({
    success: true,
    data: {
      id: apiKey.id,
      key: fullKey, 
      keyPrefix: apiKey.keyPrefix,
    },
  });
}

export async function DELETE(req: NextRequest) {
  const admin = requireAdmin(req);
  if (!admin) return NextResponse.json({ success: false, message: "Forbidden" }, { status: 403 });

  const url = new URL(req.url);
  const id = url.searchParams.get("id");

  if (!id) return NextResponse.json({ success: false, message: "id required" }, { status: 400 });

  await prisma.apiKey.delete({ where: { id } });

  return NextResponse.json({ success: true, message: "API key revoked" });
}
