// Devanagari digit maps
const devanagariDigits = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"];

export function toDevanagari(val: number | string): string {
  const str = String(val);
  return str.replace(/[0-9]/g, (digit) => devanagariDigits[parseInt(digit, 10)]);
}

export function fromDevanagari(val: string): string {
  const devToEng: Record<string, string> = {
    "०": "0", "१": "1", "२": "2", "३": "3", "४": "4",
    "५": "5", "६": "6", "७": "7", "८": "8", "९": "9",
  };
  return val.replace(/[०-९]/g, (char) => devToEng[char] ?? char);
}

